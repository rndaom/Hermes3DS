"""Generate app/test/vectors.h from plugin/tests/vectors/noise_ik.json, plus codec cases computed with the
plugin's own Python helpers, so the C code is checked against exactly what the server does.

  python app/test/gen_vectors.py
"""

import base64
import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
VECTORS = ROOT / "plugin" / "tests" / "vectors" / "noise_ik.json"
OUT = Path(__file__).with_name("vectors.h")


def c_bytes(hexstr: str) -> str:
    raw = bytes.fromhex(hexstr)
    if not raw:
        return "NULL, 0"
    return '(const uint8_t *)"' + "".join(f"\\x{b:02x}" for b in raw) + f'", {len(raw)}'


def fingerprint(key: bytes) -> str:  # same as plugin/h3proto/pairing.py
    return base64.b32encode(hashlib.blake2b(key, digest_size=32).digest()).decode()[:8]


def main() -> None:
    data = json.loads(VECTORS.read_text("utf-8"))["vectors"]
    lines = ["// Generated by gen_vectors.py from plugin/tests/vectors/noise_ik.json. Do not edit.", "#pragma once",
             "#include <stddef.h>", "#include <stdint.h>", "",
             "typedef struct { const uint8_t *p; size_t n; } Bytes;",
             "typedef struct { Bytes payload, ciphertext; } VecMsg;",
             "typedef struct { Bytes prologue, init_static, init_ephemeral, init_remote_static, resp_static,",
             "                 handshake_hash; int n_msgs; VecMsg msgs[8]; } Vector;", ""]
    lines.append("static const Vector VECTORS[] = {")
    for v in data:
        assert v["init_prologue"] == v["resp_prologue"]
        assert len(v["messages"]) <= 8
        assert not any(v.get(k) for k in ("init_psks", "resp_psks")), "PSK vectors are not IK"
        msgs = ", ".join(f"{{{{{c_bytes(m['payload'])}}}, {{{c_bytes(m['ciphertext'])}}}}}" for m in v["messages"])
        lines.append(f"    {{{{{c_bytes(v['init_prologue'])}}}, {{{c_bytes(v['init_static'])}}}, "
                     f"{{{c_bytes(v['init_ephemeral'])}}}, {{{c_bytes(v['init_remote_static'])}}}, "
                     f"{{{c_bytes(v['resp_static'])}}}, {{{c_bytes(v.get('handshake_hash', ''))}}}, "
                     f"{len(v['messages'])}, {{{msgs}}}}},")
    lines.append("};")
    lines.append(f"#define N_VECTORS {len(data)}")
    lines.append("")

    # Codec cases: fingerprints and base32/base64url as the plugin computes them.
    lines.append("typedef struct { Bytes key; const char *fp, *b64u; } FpCase;")
    lines.append("static const FpCase FP_CASES[] = {")
    for v in data:
        key = bytes.fromhex(v["init_remote_static"])
        b64 = base64.urlsafe_b64encode(key).rstrip(b"=").decode()
        lines.append(f'    {{{{{c_bytes(key.hex())}}}, "{fingerprint(key)}", "{b64}"}},')
    lines.append("};")
    tokens = [bytes(range(5)), b"\xff\xfe\x10\x20\x30", hashlib.sha256(b"hermes").digest()[:5]]
    lines.append("typedef struct { Bytes token; const char *code; } CodeCase;")
    lines.append("static const CodeCase CODE_CASES[] = {")
    for t in tokens:
        lines.append(f'    {{{{{c_bytes(t.hex())}}}, "{base64.b32encode(t).decode().rstrip("=")}"}},')
    lines.append("};")
    OUT.write_text("\n".join(lines) + "\n", "utf-8")
    print(f"wrote {OUT} ({len(data)} vectors)", file=sys.stderr)


if __name__ == "__main__":
    main()
